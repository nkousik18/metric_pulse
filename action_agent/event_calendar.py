"""
Trusted calendar context for the Action Agent (docs/action-agent-scope.md §14).

The proposer used to see a bare `anomaly_date`, so a Black Friday spike or a Monday rebound
looked like any incident and got a notify_owner. This module adds what the date *is*: its weekday
(and the comparison date's), and any calendar entry on it or within ±3 days.

Trust: the calendar comes only from a committed file per dataset,
`action_agent/calendars/<dataset_id>.yaml`, never from the data being investigated. Each file is
generated by this module from public holiday law and fixed date rules (`--write`), covering every
year of its dataset, and was committed before the golden set was re-run (§14.2's overfitting
guard: no entry is ever added because a golden case failed). A dataset with no file (any
onboarded dataset, including the adversarial one) gets an empty calendar: weekday facts only.

policy_check reads the same context from the evidence (`evidence['calendar']`), which
`attach_calendar` always recomputes from the file, so a caller can't supply its own.

    python -m action_agent.event_calendar --write    # regenerate the committed calendar files
    python -m action_agent.event_calendar --check    # do the committed files match the rules?
"""

import argparse
import re
import sys
from datetime import date, timedelta
from pathlib import Path
from typing import Callable, Dict, Iterable, List, Optional

sys.path.insert(0, str(Path(__file__).parent.parent))

import yaml  # noqa: E402

CALENDAR_DIR = Path(__file__).parent / 'calendars'
WINDOW_DAYS = 3
WEEKDAYS = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday']
_SAFE_ID = re.compile(r'^[A-Za-z0-9_-]{1,100}$')


# --------------------------------------------------------------------------- lookup

def load_calendar(dataset_id: str, calendar_dir: Path = CALENDAR_DIR) -> Dict:
    """{'source': str|None, 'events': [{date, name, kind}]}. Empty for an unknown dataset or an
    id that isn't a plain name (never a path outside calendar_dir)."""
    if not isinstance(dataset_id, str) or not _SAFE_ID.match(dataset_id):
        return {'source': None, 'events': []}
    path = Path(calendar_dir) / f'{dataset_id}.yaml'
    if not path.exists():
        return {'source': None, 'events': []}
    data = yaml.safe_load(path.read_text()) or {}
    events = [{'date': str(e['date']), 'name': e['name'], 'kind': e['kind']} for e in data.get('events') or []]
    return {'source': data.get('source'), 'events': events}


def _parse(day) -> Optional[date]:
    try:
        return date.fromisoformat(str(day)[:10])
    except (TypeError, ValueError):
        return None


def _is_weekend(d: date) -> bool:
    return d.weekday() >= 5


def calendar_context(dataset_id: str, anomaly_date, previous_date,
                     calendar_dir: Path = CALENDAR_DIR, window: int = WINDOW_DAYS) -> Dict:
    """The `calendar` block of the proposer's evidence (§14.1).

    offset_days is the event's date minus the anomaly date, so the day after Black Friday shows
    Black Friday at -1. events_nearby excludes offset 0 (those are events_on_date)."""
    cal = load_calendar(dataset_id, calendar_dir)
    day, prev = _parse(anomaly_date), _parse(previous_date)
    context = {
        'source': cal['source'],
        'weekday': WEEKDAYS[day.weekday()] if day else None,
        'previous_weekday': WEEKDAYS[prev.weekday()] if prev else None,
        # Weekend vs. weekday differs between the two compared dates: a weekly pattern.
        'weekday_class_changed': bool(day and prev and _is_weekend(day) != _is_weekend(prev)),
        'events_on_date': [],
        'events_nearby': [],
    }
    if day is None:
        return context
    for e in cal['events']:
        d = _parse(e['date'])
        if d is None:
            continue
        offset = (d - day).days
        if offset == 0:
            context['events_on_date'].append(dict(e))
        elif abs(offset) <= window:
            context['events_nearby'].append({**e, 'offset_days': offset})
    context['events_nearby'].sort(key=lambda e: (abs(e['offset_days']), e['offset_days']))
    return context


def attach_calendar(evidence: Dict, dataset_id: str, anomaly_date,
                    calendar_dir: Path = CALENDAR_DIR) -> Dict:
    """A copy of evidence with `calendar` recomputed from the trusted file (any `calendar` the
    caller passed in is replaced)."""
    out = dict(evidence or {})
    out['calendar'] = calendar_context(dataset_id, anomaly_date, out.get('previous_date'), calendar_dir)
    return out


def event_names(calendar: Optional[Dict]) -> List[str]:
    """Names a calendar_event param may cite: entries on the date or within the window."""
    calendar = calendar or {}
    return [e['name'] for e in (calendar.get('events_on_date') or []) + (calendar.get('events_nearby') or [])]


# --------------------------------------------------------------------------- generating the files

def easter(year: int) -> date:
    """Gregorian Easter Sunday (the anonymous Gregorian / Meeus-Jones-Butcher algorithm)."""
    a, b, c = year % 19, year // 100, year % 100
    d, e = b // 4, b % 4
    f = (b + 8) // 25
    g = (b - f + 1) // 3
    h = (19 * a + b - d - g + 15) % 30
    i, k = c // 4, c % 4
    l_ = (32 + 2 * e + 2 * i - h - k) % 7
    m = (a + 11 * h + 22 * l_) // 451
    month = (h + l_ - 7 * m + 114) // 31
    day = ((h + l_ - 7 * m + 114) % 31) + 1
    return date(year, month, day)


def nth_weekday(year: int, month: int, weekday: int, n: int) -> date:
    """The n-th `weekday` (0=Monday) of a month."""
    first = date(year, month, 1)
    return first + timedelta(days=(weekday - first.weekday()) % 7 + 7 * (n - 1))


def black_friday(year: int) -> date:
    """The day after US Thanksgiving (the 4th Thursday of November)."""
    return nth_weekday(year, 11, 3, 4) + timedelta(days=1)


def _event(d: date, name: str, kind: str) -> Dict:
    return {'date': d.isoformat(), 'name': name, 'kind': kind}


def brazil_events(year: int) -> List[Dict]:
    """Brazilian national public holidays (Lei 662/1949 as amended by Lei 10.607/2002; Lei
    6.802/1980 for 12 Oct; Good Friday under Lei 9.093/1995), plus retail dates by rule. Carnival
    and state/municipal holidays are deliberately out (Kousik, 2026-11-04)."""
    return [
        _event(date(year, 1, 1), "New Year's Day", 'holiday'),
        _event(easter(year) - timedelta(days=2), 'Good Friday', 'holiday'),
        _event(date(year, 4, 21), 'Tiradentes Day', 'holiday'),
        _event(date(year, 5, 1), 'Labour Day', 'holiday'),
        _event(nth_weekday(year, 5, 6, 2), "Mother's Day", 'retail_event'),
        _event(nth_weekday(year, 8, 6, 2), "Father's Day", 'retail_event'),
        _event(date(year, 9, 7), 'Independence Day', 'holiday'),
        _event(date(year, 10, 12), 'Our Lady of Aparecida', 'holiday'),
        _event(date(year, 11, 2), "All Souls' Day", 'holiday'),
        _event(date(year, 11, 15), 'Proclamation of the Republic', 'holiday'),
        _event(black_friday(year), 'Black Friday', 'retail_event'),
        _event(date(year, 12, 24), 'Christmas Eve', 'retail_event'),
        _event(date(year, 12, 25), 'Christmas Day', 'holiday'),
    ]


def canada_events(year: int) -> List[Dict]:
    """Canadian federal general holidays (Canada Labour Code s.166), on the dates they fall,
    plus Black Friday. Boxing Day is already one of the s.166 holidays."""
    may25 = date(year, 5, 25)
    victoria = may25 - timedelta(days=may25.weekday() or 7)   # the last Monday before 25 May
    return [
        _event(date(year, 1, 1), "New Year's Day", 'holiday'),
        _event(easter(year) - timedelta(days=2), 'Good Friday', 'holiday'),
        _event(victoria, 'Victoria Day', 'holiday'),
        _event(date(year, 7, 1), 'Canada Day', 'holiday'),
        _event(nth_weekday(year, 9, 0, 1), 'Labour Day', 'holiday'),
        _event(nth_weekday(year, 10, 0, 2), 'Thanksgiving', 'holiday'),
        _event(date(year, 11, 11), 'Remembrance Day', 'holiday'),
        _event(black_friday(year), 'Black Friday', 'retail_event'),
        _event(date(year, 12, 25), 'Christmas Day', 'holiday'),
        _event(date(year, 12, 26), 'Boxing Day', 'holiday'),
    ]


# dataset_id -> (rule, years covered, source line written into the file)
SPECS: Dict[str, tuple] = {
    'olist': (brazil_events, range(2016, 2019),
              'Brazilian national public holidays (Lei 662/1949, Lei 6.802/1980, Lei 9.093/1995, '
              "Lei 10.607/2002) plus Black Friday (day after US Thanksgiving), Mother's Day (2nd Sunday "
              "of May), Father's Day (2nd Sunday of August) and Christmas Eve. Data: 2016-09 to 2018-09."),
    'superstore_sales': (canada_events, range(2009, 2013),
                         'Canadian federal general holidays (Canada Labour Code s.166), on the dates they '
                         'fall, plus Black Friday (day after US Thanksgiving). Data: 2009 to 2012.'),
}

HEADER = """\
# Trusted calendar for the Action Agent's proposer (docs/action-agent-scope.md §14).
# GENERATED by `python -m action_agent.event_calendar --write` from public holiday law and fixed
# date rules; never derived from the data. Don't hand-edit. An entry added for any other reason
# must be logged with its reason in the scope doc §14.
"""


def build(rule: Callable[[int], List[Dict]], years: Iterable[int], source: str) -> Dict:
    events = sorted((e for y in years for e in rule(y)), key=lambda e: (e['date'], e['name']))
    return {'source': source, 'events': events}


def render(dataset_id: str) -> str:
    rule, years, source = SPECS[dataset_id]
    return HEADER + yaml.safe_dump(build(rule, years, source), sort_keys=False, allow_unicode=True, width=110)


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description='Action Agent calendars (scope §14)')
    parser.add_argument('--write', action='store_true', help='Regenerate the committed calendar files')
    parser.add_argument('--check', action='store_true', help='Check the committed files match the rules')
    parser.add_argument('--dir', type=Path, default=CALENDAR_DIR)
    args = parser.parse_args(argv)
    stale = []
    for dataset_id in SPECS:
        path = args.dir / f'{dataset_id}.yaml'
        text = render(dataset_id)
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f'wrote {path} ({len(build(*SPECS[dataset_id])["events"])} entries)')
        elif not path.exists() or path.read_text() != text:
            stale.append(dataset_id)
    if args.check:
        print(f'stale or missing: {stale}' if stale else 'calendars match their rules')
        sys.exit(1 if stale else 0)


if __name__ == '__main__':
    main()
