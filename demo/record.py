"""
Record real API responses for the static replay site (docs/hosting-scope.md §6.1, milestone H1).

    python -m demo.record                         # everything; real Groq calls (~6), needs a clean tree
    python -m demo.record --check                 # Q2: re-record the no-LLM files, compare to the committed ones

Drives the **real** Django views through django.test.Client: no server, no mocks, no hand-written
data (rule R1). Each response is saved under demo/recordings/ with an index.json mapping the
request key (demo/keys.py) to its file, plus a manifest.json saying when, at which commit, with
which models and prompts, and by which command it was recorded.

Isolation: before anything from the project is imported, the environment points the Action
Agent's databases and the alert outbox at a scratch directory, so recording never touches the real
actions.db, checkpoints.db or outbox/, and live effects stay off (every decision is sent with
`live: false`). The one transformation applied to responses is replacing that scratch path with
"<scratch>", so no local path is published.

What's deterministic (Q2, on the same commit and warehouse): metrics, anomalies, decomposition,
narrative, onboarding and evals, byte-for-byte except one line: the narrative template stamps
"*Generated by MetricPulse at <time>*" (narrative/generator.py), which `--check` masks and nothing
else. Not deterministic: investigate and actions (LLM output, UUIDs, timestamps) and pipeline (it
reports its own duration).
"""

