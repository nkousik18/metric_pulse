def configure_environment(scratch: Path) -> None:
    os.environ.update({
        'DJANGO_SETTINGS_MODULE': 'metric_pulse_web.settings',
        'ACTION_APPROVER_TOKEN': TOKEN,
        'ACTION_APPROVER': APPROVER,
        'ACTIONS_DB_PATH': str(scratch / 'actions.db'),
        'CHECKPOINTS_DB_PATH': str(scratch / 'checkpoints.db'),
        'OUTBOX_DIR': str(scratch / 'outbox'),
        'ALERT_CHANNEL': 'outbox',
        'CLOUDWATCH_METRICS': 'false',
        'WAREHOUSE': 'duckdb',
    })
    sys.path.insert(0, str(ROOT))
    import django
    django.setup()


def tree_is_clean() -> bool:
    """Tracked files unchanged, apart from the recordings themselves (re-recording rewrites them)."""
    out = subprocess.run(
        ['git', 'status', '--porcelain', '--untracked-files=no', '--', '.', ':!demo/recordings'],
        cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return not out.strip()


# --- the recorder ---

class Recorder:
    def __init__(self, out_dir: Path, scratch: Path):
        from django.core.cache import cache
        from django.test import Client
        self.client, self.cache = Client(), cache
        self.out_dir, self.scratch = out_dir, scratch
        self.index: Dict[str, Dict] = {}

    def _scrub(self, payload):
        text = json.dumps(payload, ensure_ascii=False)
        for path in {str(self.scratch), str(self.scratch.resolve())}:
            text = text.replace(path, '<scratch>')
        return json.loads(text)

    def save(self, rel: str, payload) -> str:
        path = self.out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(self._scrub(payload), indent=1, sort_keys=True, ensure_ascii=False) + '\n')
        return rel

    def call(self, method: str, url: str, body: Optional[Dict] = None, auth: bool = False) -> Tuple[int, Dict]:
        self.cache.clear()   # the per-IP throttles would otherwise trip on a recording run
        headers = {'HTTP_AUTHORIZATION': f'Bearer {TOKEN}'} if auth else {}
        if method == 'GET':
            response = self.client.get(url, **headers)
        else:
            response = self.client.post(url, json.dumps(body or {}), content_type='application/json', **headers)
        return response.status_code, json.loads(response.content)

    def record(self, method: str, url: str, rel: str, body: Optional[Dict] = None,
               expect_ok: bool = True) -> Dict:
        from demo.keys import request_key
        code, payload = self.call(method, url, body)
        if expect_ok and (code != 200 or payload.get('status') != 'success'):
            raise RuntimeError(f'{method} {url} {body or ""} -> {code}: {payload.get("message", payload)}')
        self.index[request_key(method, url, body)] = {'file': self.save(rel, payload), 'status': code}
        return payload


def record_dashboard(rec: Recorder) -> List[str]:
    """Metrics, anomalies at every slider stop, and decomposition + narrative for the default pair
    and every consecutive pair of the 60 dates the dashboard lists."""
    metrics = rec.record('GET', f'/api/metrics/?days={METRICS_DAYS}', f'metrics/days-{METRICS_DAYS}.json')
    dates = [row['metric_date'] for row in metrics['data']]     # newest first, as the SPA shows them
    for t in THRESHOLDS:
        rec.record('GET', f'/api/anomalies/?threshold={t}', f'anomalies/threshold-{t}.json')
    for endpoint in ('decomposition', 'narrative'):
        rec.record('GET', f'/api/{endpoint}/', f'{endpoint}/default.json')
        for current, previous in zip(dates, dates[1:]):
            rec.record('GET', f'/api/{endpoint}/?current_date={current}&previous_date={previous}',
                       f'{endpoint}/{current}_{previous}.json')
    return dates


def record_pipeline(rec: Recorder) -> None:
    """Both pipeline buttons for each metric. "Run & Send Alert" writes to the scratch outbox."""
    for metric in METRICS:
        for force_alert in (False, True):
            body = {'metric': metric, 'force_alert': force_alert, 'dry_run': not force_alert}
            mode = 'send-alert' if force_alert else 'dry-run'
            rec.record('POST', '/api/pipeline/', f'pipeline/{metric}_{mode}.json', body)


def record_investigations(rec: Recorder) -> List[Dict]:
    """Real Groq calls, one per case, with the LangSmith trace link when tracing is on."""
    from langchain_core.tracers.context import collect_runs
    out = []
    for case in CASES:
        body = {'metric': case['metric'], 'current_date': case['current_date'],
                'previous_date': case['previous_date']}
        with collect_runs() as runs:
            payload = rec.record('POST', '/api/investigate/',
                                 f'investigate/{case["metric"]}_{case["current_date"]}_{case["previous_date"]}.json', body)
        data = payload['data']
        if data.get('status') == 'failed':
            raise RuntimeError(f'investigation {case["id"]} failed: {data.get("error")}')
        root = runs.traced_runs[0].id if runs.traced_runs else None
        out.append({**case, 'status': data.get('status'), 'grounding_failed': bool(data.get('grounding_failed')),
                    'trace_url': _trace_url(root)})
    return out


def _trace_url(run_id) -> Optional[str]:
    from observability.tracing import trace_url, tracing_enabled
    if not tracing_enabled() or run_id is None:
        return None
    try:
        from langchain_core.tracers.langchain import wait_for_all_tracers
        wait_for_all_tracers()
    except Exception:   # best effort: a missing link never fails a recording
        pass
    return trace_url(run_id)


# --- the Action Agent: real proposals, then one approval walk-through ---

def edited_params(action_type: str, params: Dict) -> Optional[Dict]:
    """A small, policy-valid change an approver might make, or None if this type has none."""
    from action_agent.schemas import CONTROL_MAX_EXPIRY_DAYS, SUPPRESS_MAX_DAYS
    p = dict(params)
    if action_type == 'suppress_alerts':
        p['days'] = p['days'] + 1 if p['days'] < SUPPRESS_MAX_DAYS else p['days'] - 1
    elif action_type == 'create_control':
        days = p['expires_in_days']
        p['expires_in_days'] = days + 7 if days + 7 <= CONTROL_MAX_EXPIRY_DAYS else max(1, days - 7)
    elif action_type == 'open_incident':
        p['severity'] = {'low': 'medium', 'medium': 'high', 'high': 'medium'}[p['severity']]
    elif action_type == 'annotate_anomaly':
        note = ' (confirmed by the approver)'
        p['cause'] = p['cause'][:200 - len(note)] + note
    else:
        return None
    return p


def plan_walkthrough(pending: List[Dict]) -> Dict:
    """Which proposal is approved, which edited, which rejected, and which of the first two is then
    undone. Undo needs a reversible type, edit needs one edited_params() can change."""
    from action_agent.catalog import CATALOG

    def kind(item):
        return item['waiting_on']['dry_run']['action_type']

    def rank(item):
        return REVERSIBLE_PREFERENCE.index(kind(item)) if kind(item) in REVERSIBLE_PREFERENCE else 99

    options = []
    for approve, edit, reject in permutations(pending, 3):
        if not edited_params(kind(edit), edit['waiting_on']['dry_run']['params']):
            continue
        for undo in (approve, edit):
            if CATALOG[kind(undo)].reversible:
                options.append((rank(undo), undo is edit,
                                {'approve': approve, 'edit': edit, 'reject': reject, 'undo': undo}))
    if not options:
        raise RuntimeError('the recorded proposals cannot cover approve, edit, reject and undo: '
                           f'{[kind(p) for p in pending]}. Re-run, or change CASES.')
    return min(options, key=lambda o: o[:2])[2]   # prefer undoing a plain approval


def record_actions(rec: Recorder) -> Dict:
    from action_agent.evidence import build_case
    from action_agent.llm_proposer import make_llm_proposer
    from action_agent.runner import ActionAgent
    from observability.tracing import trace_url

    proposals = []
    for case in CASES:
        agent = ActionAgent(proposer_fn=make_llm_proposer())
        try:
            started = agent.start(**build_case('olist', case['metric'], case['current_date']))
        finally:
            agent.close()
        if started.get('status') != 'awaiting_approval':
            raise RuntimeError(f'proposal for {case["id"]} is {started.get("status")}, not awaiting approval')
        proposals.append({'case': case['id'], 'proposal_id': started['proposal_id'],
                          'trace_url': trace_url(started.get('trace_id'))})

    def snapshot():
        _, pending = rec.call('GET', '/api/actions/pending/', auth=True)
        _, log = rec.call('GET', '/api/actions/log/?limit=100', auth=True)
        return {'pending': pending, 'log': log}

    initial = snapshot()
    plan = plan_walkthrough(initial['pending']['data'])
    approve, edit, reject, undo = (plan[k]['proposal_id'] for k in ('approve', 'edit', 'reject', 'undo'))
    edit_type = plan['edit']['waiting_on']['dry_run']['action_type']
    new_params = edited_params(edit_type, plan['edit']['waiting_on']['dry_run']['params'])

    script = [
        (approve, 'approve', {'reason': 'Approved as proposed (recorded demo).', 'live': False}),
        (edit, 'edit', {'reason': 'Adjusted the parameters before approving (recorded demo).',
                        'live': False, 'params': new_params}),
        (reject, 'reject', {'reason': 'Not worth acting on (recorded demo).', 'live': False}),
        (undo, 'undo', {'reason': 'Reversed after review (recorded demo).', 'live': False}),
    ]
    # Real validation answers, so the replay can show them when a reason is left empty.
    validation = {}
    for verb, message_key in (('reject', 'reject'), ('undo', 'undo')):
        code, payload = rec.call('POST', f'/api/actions/{reject if verb == "reject" else undo}/{verb}/',
                                 {'reason': '', 'live': False}, auth=True)
        if code != 400:
            raise RuntimeError(f'expected a 400 for a {verb} without a reason, got {code}')
        validation[message_key] = {'status': code, 'body': payload}

    steps = []
    for pid, verb, body in script:
        code, payload = rec.call('POST', f'/api/actions/{pid}/{verb}/', body, auth=True)
        if code != 200 or payload['data'].get('status') == 'awaiting_approval':
            raise RuntimeError(f'{verb} {pid} -> {code}: {payload}')
        steps.append({'proposal_id': pid, 'verb': verb, 'body': body,
                      'response': {'status': code, 'body': payload}, 'after': snapshot()})

    flow = {'proposals': proposals, 'initial': initial, 'steps': steps, 'validation': validation}
    rec.save('actions/flow.json', flow)
    return {'proposals': proposals, 'walkthrough': [{'proposal_id': s['proposal_id'], 'verb': s['verb']}
                                                    for s in steps]}


# --- onboarding (Superstore, M6) and evals ---

def record_onboarding(rec: Recorder) -> None:
    from action_agent.runner import to_plain
    from onboarding.codegen import GENERATED_DIR
    from onboarding.investigate import run_cycle

    classification = GENERATED_DIR / SUPERSTORE_DATASET / 'classification.json'
    if not classification.exists():
        raise RuntimeError(f'{classification} is missing: run the M6 onboarding of Superstore first '
                           '(python -m onboarding.onboard --file <superstore csv>)')
    results = {}
    for metric in SUPERSTORE_METRICS:
        cycle = to_plain(run_cycle(SUPERSTORE_DATASET, metric))
        if cycle.get('status') == 'failed':
            raise RuntimeError(f'superstore {metric}: {cycle.get("error")}')
        results[metric] = cycle
    rec.save('onboarding/superstore_sales.json', {
        'dataset_id': SUPERSTORE_DATASET,
        'classification': json.loads(classification.read_text()),
        'results': results,
    })


def record_evals(rec: Recorder) -> None:
    from observability.drift import latest_rows
    from observability.evals import load_baseline, read_ledger
    rows = latest_rows(read_ledger())
    rec.save('evals/latest.json', {name: {'latest': row, 'baseline': load_baseline(name)}
                                   for name, row in sorted(rows.items())})


# --- Q2: reproducibility check ---

GENERATED_STAMP = re.compile(r'Generated by MetricPulse at \d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}')
DETERMINISTIC = ['metrics', 'anomalies', 'decomposition', 'narrative', 'onboarding', 'evals']


def compare_deterministic(committed: Path, fresh: Path) -> List[str]:
    """Files under the deterministic folders that differ (or exist on one side only), with the
    narrative's generation stamp masked."""
    def files(root):
        return {p.relative_to(root) for d in DETERMINISTIC for p in (root / d).rglob('*.json')}
    problems = []
    for rel in sorted(files(committed) | files(fresh)):
        a, b = committed / rel, fresh / rel
        if not a.exists() or not b.exists():
            problems.append(f'{rel}: only in {"fresh" if b.exists() else "committed"} recording')
        elif GENERATED_STAMP.sub('', a.read_text()) != GENERATED_STAMP.sub('', b.read_text()):
            problems.append(f'{rel}: differs')
    return problems


# --- manifest ---

def llm_calls_since(offset: int) -> List[Dict]:
    from config import settings
    path = Path(settings.LLM_CALLS_LOG)
    if not path.exists():
        return []
    with path.open('rb') as f:
        f.seek(offset)
        return [json.loads(line) for line in f.read().decode().splitlines() if line.strip()]


def summarize_llm_calls(calls: List[Dict]) -> Dict:
    return {
        'count': len(calls),
        'models': sorted({c['model'] for c in calls}),
        'prompt_hashes': sorted({f"{c['stage']}:{c['prompt_hash']}" for c in calls if c.get('prompt_hash')}),
        'total_tokens': sum(c.get('total_tokens') or 0 for c in calls),
        'cost_usd': round(sum(c.get('cost_usd') or 0 for c in calls), 6),
    }


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--only', choices=['all', 'deterministic'], default='all',
                        help='deterministic: metrics, anomalies, decomposition, narrative, onboarding, '
                             'evals (no LLM calls), for checking Q2')
    parser.add_argument('--out', type=Path, default=RECORDINGS_DIR)
    parser.add_argument('--check', action='store_true',
                        help='Q2: record the deterministic files to a temp dir and compare them with --out')
    parser.add_argument('--allow-dirty', action='store_true',
                        help='record on uncommitted changes (the manifest says -dirty); for development only')
    args = parser.parse_args(argv)
    committed = args.out
    if args.check:
        args.only, args.out = 'deterministic', Path(tempfile.mkdtemp(prefix='metricpulse-check-'))

    if not args.check and not args.allow_dirty and not tree_is_clean():
        sys.exit('Refusing to record on a dirty tree: commit first, so the recording maps to a commit.')

    scratch = Path(tempfile.mkdtemp(prefix='metricpulse-record-'))
    configure_environment(scratch)
    from config import settings
    from observability.evals import git_sha_dirty, llm_log_offset

    staging = Path(tempfile.mkdtemp(prefix='metricpulse-recordings-'))
    rec = Recorder(staging, scratch)
    offset = llm_log_offset()
    manifest = {
        'recorded_at': datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        'git_sha': git_sha_dirty(ROOT),
        'command': COMMAND + ('' if args.only == 'all' else f' --only {args.only}'),
        'warehouse': settings.WAREHOUSE,
        'deterministic': DETERMINISTIC,
        'live_effects': False,
        'olist_attribution': 'Olist Brazilian E-Commerce Public Dataset, CC BY-NC-SA 4.0',
    }
    try:
        dates = record_dashboard(rec)
        manifest['dates'] = {'newest': dates[0], 'oldest': dates[-1], 'count': len(dates)}
        record_onboarding(rec)
        record_evals(rec)
        if args.only == 'all':
            record_pipeline(rec)
            manifest['investigations'] = record_investigations(rec)
            manifest['actions'] = record_actions(rec)
            manifest['llm_calls'] = summarize_llm_calls(llm_calls_since(offset))
            manifest['models'] = {'investigation': settings.GROQ_MODEL,
                                  'action_small': settings.ACTION_SMALL_MODEL,
                                  'action_large': settings.ACTION_LARGE_MODEL}
        rec.save('index.json', rec.index)
        if args.only == 'all':
            rec.save('manifest.json', manifest)
        if args.out.exists():
            shutil.rmtree(args.out)
        shutil.copytree(staging, args.out)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
        shutil.rmtree(scratch, ignore_errors=True)

    if args.check:
        problems = compare_deterministic(committed, args.out)
        shutil.rmtree(args.out, ignore_errors=True)
        for line in problems:
            print(line)
        sys.exit(f'Q2 failed: {len(problems)} file(s) differ.' if problems
                 else f'Q2 passed: the deterministic recordings in {committed} reproduce.')

    n = sum(1 for _ in args.out.rglob('*.json'))
    print(f'Recorded {n} files to {args.out} at {manifest["git_sha"]}.')
    if 'llm_calls' in manifest:
        c = manifest['llm_calls']
        print(f'LLM calls: {c["count"]}, {c["total_tokens"]} tokens, ${c["cost_usd"]}.')


if __name__ == '__main__':
    main()
